<?php

use runtime\api\RuntimeAPI;
use runtime\enums\ERuntimeFlags;
use ThemeEngine\service\Engine;

final class CMSBundle extends RuntimeAPI
{
    public function environmentSetup(): void
    {
        parent::environmentSetup(); // TODO: Change the autogenerated stub
        $this->setRuntimeFlag(ERuntimeFlags::WaitForPackage);
    }

    public function setup(): void
    {
        if (!file_exists($this->runtimePath . '/installed.php')) {
            $this->waitForRuntime("ThemeEngine");
        }
    }

    public function main(): void
    {
        $installed = $this->runtimePath . '/installed.php';
        if (file_exists($installed)) {
            return;
        }

        $engine = $this->getShared('ThemeEngine', 'engine', Engine::class)
            ?? throw new \LogicException('Missing ThemeEngine engine.');

        if ($engine->hasActiveTheme()) {
            touch($installed);
            return;
        }

        foreach ($engine->registry->all() as $theme) {
            if ($theme->enabled) {
                $engine->activate($theme->packageId);
                touch($installed);
                return;
            }
        }
    }
}
